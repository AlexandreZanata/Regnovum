// TestProvenanceIsReadWhereTheToolchainReadsIt proves the exclusion in the three
// shapes a repository actually contains: the marker before the package clause
// (excluded, even with a blank line after it, which is how sqlc writes it), the
// marker after the package clause (judged), and the marker inside a string
// (judged — the generators of this repository carry it exactly that way).
func TestProvenanceIsReadWhereTheToolchainReadsIt(t *testing.T) {
	fixtureRoot := t.TempDir()
	sources := map[string]string{
		"marked.go":   "// Code generated by sqlc. DO NOT EDIT.\n\npackage sample\n\nfunc Generated() {}\n",
		"latemark.go": "package sample\n\n// Code generated by something. DO NOT EDIT.\nfunc Later() {}\n",
		"mention.go":  "package sample\n\n// The text a generator emits, as a value.\nconst header = \"// Code generated by internal/i18ngen from locales/. DO NOT EDIT.\"\n\nfunc Judged() {}\n",
		"plain.go":    "package sample\n\nfunc Plain() {}\n",
	}
	for name, content := range sources {
		if err := os.WriteFile(filepath.Join(fixtureRoot, name), []byte(content), 0o600); err != nil {
			t.Fatalf("write %s: %v", name, err)
		}
	}
	measured, err := measureDirectory(fixtureRoot)
	if err != nil {
		t.Fatalf("measure the fixture: %v", err)
	}
	if len(measured.Generated) != 1 || filepath.Base(measured.Generated[0]) != "marked.go" {
		t.Errorf("the provenance rule excluded %v, want only marked.go", measured.Generated)
	}
	if measured.Files != 4 {
		t.Errorf("the gate read %d file(s), want the four of the fixture", measured.Files)
	}
}

// TestDuplicationFindsTheCopyAndNotTheCoincidence holds the window from both
// sides: the fixture pair is one region with two places, and a block one line
// short of the window is nothing.
func TestDuplicationFindsTheCopyAndNotTheCoincidence(t *testing.T) {
	withRoot(t, func() {
		measured, err := measureDirectory("tools/complexityaudit/testdata/duplicated")
		if err != nil {
			t.Fatalf("measure the fixture: %v", err)
		}
		regions := []finding{}
		for _, finding := range measured.Findings {
			if finding.Kind == kindDuplication {
				regions = append(regions, finding)
			}
		}
		if len(regions) != 1 {
			t.Fatalf("the fixture pair produced %d region(s), want exactly one: %+v", len(regions), regions)
		}
		if len(regions[0].Places) != 2 {
			t.Errorf("the region has %d place(s), want two (the same block with different indentation): %v", len(regions[0].Places), regions[0].Places)
		}
		if len(regions[0].Paths()) != 2 {
			t.Errorf("the region names %d file(s), want two", len(regions[0].Paths()))
		}
		if regions[0].Value < duplicationWindow {
			t.Errorf("the region is %d line(s) long and the window is %d", regions[0].Value, duplicationWindow)
		}
	})

	// The boundary, on a synthetic corpus: the same block twice, one line short
	// of the window. The lines are distinct on purpose — a corpus of identical
	// lines matches itself everywhere, which proves nothing about the window.
	short := make([]string, 0, duplicationWindow-1)
	for index := 0; index < duplicationWindow-1; index++ {
		short = append(short, fmt.Sprintf("step += value + %d", index))
	}
	lines := []dupLine{}
	for _, copy := range [][]string{short, short} {
		for _, text := range copy {
			lines = append(lines, dupLine{Path: "a.go", Line: len(lines) + 1, Text: text})
		}
	}
	if regions := duplicatedBlocks(lines); len(regions) != 0 {
		t.Errorf("a block one line short of the window was reported: %+v", regions)
	}
}

// TestTheDocumentIsOneEntryPerLine holds the writer to the format a reader
// reviews: the document parses back to what was written, and every entry is one
// line, so a tree with a hundred accepted findings is a hundred-line diff.
func TestTheDocumentIsOneEntryPerLine(t *testing.T) {
	baseline := &Baseline{
		Schema: baselineSchema,
		Note:   baselineNote,
		Entries: []Entry{
			{Kind: kindFunction, Path: "internal/wallet/application/send.go", Function: "Send", Metric: MetricCyclomatic, Value: 30, Owner: "internal/wallet/application"},
			{Kind: kindDuplication, Value: 22, Owner: "internal/arenas/application", Digest: "0eb1a6def3b63db6", Paths: []string{"internal/arenas/application/feed_cursor.go", "internal/wallet/application/statement_cursor.go"}},
		},
	}
	rendered := render(baseline)
	parsed := &Baseline{}
	if err := json.Unmarshal([]byte(rendered), parsed); err != nil {
		t.Fatalf("the rendered document does not parse: %v\n%s", err, rendered)
	}
	if len(parsed.Entries) != len(baseline.Entries) || parsed.Schema != baselineSchema || parsed.Note != baselineNote {
		t.Errorf("the document did not survive the round trip: %+v", parsed)
	}
	for _, entry := range baseline.Entries {
		encoded, err := json.Marshal(entry)
		if err != nil {
			t.Fatalf("encode the entry: %v", err)
		}
		matches := 0
		for _, line := range strings.Split(rendered, "\n") {
			if trimmed := strings.TrimSpace(line); trimmed == string(encoded) || trimmed == string(encoded)+"," {
				matches++
			}
		}
		if matches != 1 {
			t.Errorf("the entry %s occupies %d line(s), want exactly one", encoded, matches)
		}
	}
}
