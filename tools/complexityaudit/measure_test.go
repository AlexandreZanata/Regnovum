// Tests of the measurement: what the gate counts, where it reads the generated
// marker, and which copies it recognizes.
package main

import (
	"encoding/json"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// fixtureValues takes every measure of one function of one fixture. The numbers
// are the contract: a fixture with thirty branches has cyclomatic 31, and the day
// the count moves is the day this test says so.
func fixtureValues(t *testing.T, fixture, function string) map[string]int {
	t.Helper()
	files, err := filepath.Glob(filepath.Join("testdata", fixture, "*.go"))
	if err != nil {
		t.Fatalf("list the fixture %s: %v", fixture, err)
	}
	if len(files) == 0 {
		t.Fatalf("the fixture %s holds no Go file", fixture)
	}
	for _, file := range files {
		source, err := os.ReadFile(file)
		if err != nil {
			t.Fatalf("read %s: %v", file, err)
		}
		positions := token.NewFileSet()
		parsed, err := parser.ParseFile(positions, file, source, parser.ParseComments)
		if err != nil {
			t.Fatalf("parse %s: %v", file, err)
		}
		for _, declaration := range parsed.Decls {
			declared, ok := declaration.(*ast.FuncDecl)
			if !ok || declared.Body == nil {
				continue
			}
			if funcName(declared) == function {
				return functionValues(positions, declared)
			}
		}
	}
	t.Fatalf("the fixture %s declares no %s", fixture, function)
	return nil
}

// TestTheMeasuresAreTheOnesDeclared pins every measure on a fixture whose shape
// a reader can count by hand.
func TestTheMeasuresAreTheOnesDeclared(t *testing.T) {
	cases := []struct {
		fixture  string
		function string
		want     map[string]int
	}{
		{
			fixture: "complex", function: "tooManyDecisions",
			// Thirty branches and one path through them.
			want: map[string]int{MetricCyclomatic: 31, MetricNesting: 1, MetricParameters: 1, MetricLines: 93, MetricStatements: 61},
		},
		{
			fixture: "nested", function: "tooDeep",
			// Five levels of nesting, and the decisions count one per level.
			want: map[string]int{MetricNesting: 5, MetricCyclomatic: 6, MetricParameters: 1, MetricLines: 18, MetricStatements: 11},
		},
		{
			fixture: "parameters", function: "tooManyParameters",
			// Eight names, which is eight parameters to the caller even though
			// the declaration groups them into one field of one type.
			want: map[string]int{MetricParameters: 8, MetricCyclomatic: 1, MetricNesting: 0, MetricLines: 3, MetricStatements: 1},
		},
		{
			fixture: "long", function: "tooLong",
			// A flat body: size is the only thing this function exceeds.
			want: map[string]int{MetricLines: 154, MetricStatements: 152, MetricCyclomatic: 1, MetricNesting: 0, MetricParameters: 1},
		},
	}
	for _, testCase := range cases {
		measured := fixtureValues(t, testCase.fixture, testCase.function)
		for metric, want := range testCase.want {
			if measured[metric] != want {
				t.Errorf("%s/%s %s = %d, want %d: the measurement moved, and every number in the baseline moved with it",
					testCase.fixture, testCase.function, metric, measured[metric], want)
			}
		}
	}
}

